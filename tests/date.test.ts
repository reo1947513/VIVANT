import { describe, it, expect } from "vitest";
import {
  addDays,
  businessTodayJst,
  formatDateParts,
  formatJstDate,
} from "../app/lib/date";

/**
 * 日付の計算の確認。
 *
 * ここを対象にしている理由：
 *   サーバーは世界標準時で動き、日本時間との差は9時間ある。何も指定せずに
 *   日付を扱うと、日本の夜9時が「前日の昼12時」として扱われ、出勤表が1日ずれる。
 *   さらにこの店は20:00〜翌5:00の営業なので、深夜3時に見ている人にとっての
 *   「今日」は暦の上では前日にあたる。この2つが重なる場所は、
 *   目で追うだけでは間違いに気づきにくい。
 *
 * 時刻は引数で渡している（now を差し込める作りになっている）。
 * 実行した瞬間の時刻に結果が左右されると、確認そのものが日によって
 * 成功したり失敗したりして意味をなさなくなるため。
 */
describe("営業日としての今日（businessTodayJst）", () => {
  it("日本時間の昼は、その日の日付を返す", () => {
    // 2026-08-11 12:00（日本時間）＝ 03:00 UTC
    expect(businessTodayJst(new Date("2026-08-11T03:00:00Z"))).toBe("2026-08-11");
  });

  it("日本時間の夜9時は、その日の日付を返す（営業開始後）", () => {
    // 2026-08-11 21:00（日本時間）＝ 12:00 UTC
    expect(businessTodayJst(new Date("2026-08-11T12:00:00Z"))).toBe("2026-08-11");
  });

  it("日をまたいだ深夜3時は、前日の日付を返す（まだ前夜の営業中）", () => {
    // 2026-08-12 03:00（日本時間）＝ 前日 18:00 UTC
    expect(businessTodayJst(new Date("2026-08-11T18:00:00Z"))).toBe("2026-08-11");
  });

  it("朝5時ちょうどは、その日の日付に切り替わる（境界）", () => {
    // 2026-08-12 05:00（日本時間）＝ 前日 20:00 UTC
    expect(businessTodayJst(new Date("2026-08-11T20:00:00Z"))).toBe("2026-08-12");
  });

  it("朝4時59分は、まだ前日のまま（境界の直前）", () => {
    // 2026-08-12 04:59（日本時間）＝ 前日 19:59 UTC
    expect(businessTodayJst(new Date("2026-08-11T19:59:00Z"))).toBe("2026-08-11");
  });

  it("日本時間の深夜0時は、前日を返す（0時を24時と誤らない）", () => {
    // 2026-08-12 00:00（日本時間）＝ 前日 15:00 UTC
    expect(businessTodayJst(new Date("2026-08-11T15:00:00Z"))).toBe("2026-08-11");
  });
});

describe("日数の加算（addDays）", () => {
  it("翌日を返す", () => {
    expect(addDays("2026-08-11", 1)).toBe("2026-08-12");
  });

  it("前日を返す", () => {
    expect(addDays("2026-08-11", -1)).toBe("2026-08-10");
  });

  it("月をまたぐ", () => {
    expect(addDays("2026-08-31", 1)).toBe("2026-09-01");
  });

  it("年をまたぐ", () => {
    expect(addDays("2026-12-31", 1)).toBe("2027-01-01");
  });

  it("うるう年の2月29日を正しく扱う", () => {
    expect(addDays("2028-02-28", 1)).toBe("2028-02-29");
    expect(addDays("2028-02-29", 1)).toBe("2028-03-01");
  });

  it("うるう年でない年は2月28日の翌日が3月1日になる", () => {
    expect(addDays("2026-02-28", 1)).toBe("2026-03-01");
  });

  it("7日分を並べても日付が飛ばない（出勤表の1週間ぶん）", () => {
    const week = Array.from({ length: 7 }, (_, i) => addDays("2026-08-11", i));
    expect(week).toEqual([
      "2026-08-11",
      "2026-08-12",
      "2026-08-13",
      "2026-08-14",
      "2026-08-15",
      "2026-08-16",
      "2026-08-17",
    ]);
  });
});

describe("表示用の整形", () => {
  it("日付と曜日を分けて返す（出勤表の見出し用）", () => {
    // 2026-08-11 は火曜日
    expect(formatDateParts("2026-08-11")).toEqual({ date: "8/11", weekday: "火" });
  });

  it("月初は0を付けずに返す", () => {
    expect(formatDateParts("2026-09-01")).toEqual({ date: "9/1", weekday: "火" });
  });

  it("日本時間で年月日にする（記事の公開日用）", () => {
    // 2026-08-11 23:00（日本時間）＝ 14:00 UTC。世界標準時で見ると前日だが、
    // 日本時間で組み立てるため 8月11日 になる
    expect(formatJstDate("2026-08-11T14:00:00Z")).toBe("2026年8月11日");
  });
});
